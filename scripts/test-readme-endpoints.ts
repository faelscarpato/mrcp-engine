async function runTests() {
  console.log(`Starting dev-server.ts on port ${PORT}...`);
  const server = spawn(
    /^win/.test(process.platform) ? "pnpm.cmd" : "pnpm",
    ["tsx", "dev-server.ts"],
    {
      stdio: "pipe",
      env: { ...process.env, PORT: String(PORT) },
      shell: true,
    },
  );

  server.stdout.on("data", (d) => console.log(d.toString().trim()));
  server.stderr.on("data", (d) => console.error(d.toString().trim()));

  await new Promise((resolve) => setTimeout(resolve, 5000));
  console.log("Server should be running. Starting tests...");

  let passed = 0;
  const results: string[] = [];

  for (const ep of endpoints) {
    try {
      const init: RequestInit = { method: ep.method };
      if (ep.method === "POST" && ep.body) {
        init.headers = { "Content-Type": "application/json" };
        init.body = JSON.stringify(ep.body);
      }

      const res = await fetch(`http://127.0.0.1:${PORT}${ep.path}`, init);
      const ok = res.status < 500 && res.status !== 404;
      if (ok) passed++;

      const resText = await res.text();
      const summary = resText.substring(0, 100).replace(/\n/g, " ");

      results.push(
        `| \`${ep.method}\` | \`${ep.path}\` | ${ok ? "✅ PASS" : "❌ FAIL"} | ${res.status} | ${summary} |`,
      );
      console.log(`Tested ${ep.method} ${ep.path} -> ${res.status}`);
    } catch (e: any) {
      results.push(
        `| \`${ep.method}\` | \`${ep.path}\` | ❌ ERROR | N/A | ${e.message} |`,
      );
      console.error(`Error testing ${ep.method} ${ep.path}:`, e.message);
    }
  }

  server.kill();

  const report = `# MRCP Engine API Verification Report

This report was generated by automated test agents to verify compliance with the README specifications.

## Endpoint Test Results

| Method | Endpoint | Status | HTTP Code | Output Preview |
|---|---|---|---|---|
${results.join("\n")}

## Conclusion
${passed} out of ${endpoints.length} endpoints responded correctly (HTTP < 500, not 404).
${passed === endpoints.length ? "✅ The project fully meets the API specs in the README." : "❌ Some endpoints failed or are missing."}
`;

  fs.writeFileSync(path.resolve("API_VERIFICATION_REPORT.md"), report);
  console.log("Report saved to API_VERIFICATION_REPORT.md");
}

runTests().catch(console.error);
